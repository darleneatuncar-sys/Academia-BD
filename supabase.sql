-- ============================================
-- 2. CREAR TABLA DISCIPLINA
-- Guarda los deportes o actividades de la academia
-- ============================================

CREATE TABLE disciplina (
    id_disciplina INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_disciplina VARCHAR(60) NOT NULL,
    horario VARCHAR(60) NOT NULL,
    nivel VARCHAR(30) NOT NULL
);


-- ============================================
-- 3. CREAR TABLA ALUMNO
-- Guarda los datos personales de cada alumno
-- ============================================

CREATE TABLE alumno (
    id_alumno INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(8) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    telefono VARCHAR(15) NOT NULL,

    CONSTRAINT chk_dni CHECK (dni ~ '^[0-9]{8}$')
);


-- ============================================
-- 4. CREAR TABLA ENTRENADOR
-- Cada entrenador está relacionado con una disciplina
-- ============================================

CREATE TABLE entrenador (
   id_entrenador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    telefono VARCHAR(15) NOT NULL,
    id_disciplina INTEGER NOT NULL,

    FOREIGN KEY (id_disciplina)
        REFERENCES disciplina(id_disciplina)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- ============================================
-- 5. CREAR TABLA INSCRIPCION
-- Relaciona a los alumnos con las disciplinas
-- ============================================

CREATE TABLE inscripcion (
    id_inscripcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_alumno INTEGER,
    id_disciplina INTEGER,

    fecha_inscripcion DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'Activa',

    FOREIGN KEY (id_alumno)
        REFERENCES alumno(id_alumno)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    FOREIGN KEY (id_disciplina)
        REFERENCES disciplina(id_disciplina)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT chk_estado
        CHECK (estado IN ('Activa', 'Inactiva'))
);


