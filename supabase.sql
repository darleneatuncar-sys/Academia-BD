-- ============================================
-- 10. FUNCION PARA REGISTRAR UNA INSCRIPCION
-- Recibe los datos del alumno y la disciplina.
-- Registra al alumno y luego crea su inscripción.
-- Si el DNI ya existe, reutiliza ese alumno.
-- ============================================

CREATE OR REPLACE FUNCTION public.registrar_inscripcion(
    p_dni TEXT,
    p_nombre TEXT,
    p_apellido TEXT,
    p_telefono TEXT,
    p_id_disciplina INTEGER
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_id_alumno INTEGER;
    v_id_inscripcion INTEGER;
BEGIN

    -- Validar que los campos no estén vacíos
    IF p_dni IS NULL OR p_dni !~ '^[0-9]{8}$' THEN
        RAISE EXCEPTION 'El DNI debe tener exactamente 8 digitos';
    END IF;

    IF TRIM(p_nombre) = '' OR
       TRIM(p_apellido) = '' OR
       TRIM(p_telefono) = '' THEN
        RAISE EXCEPTION 'Completa todos los datos del alumno';
    END IF;

    -- Comprobar que la disciplina exista
    IF NOT EXISTS (
        SELECT 1
        FROM disciplina
        WHERE id_disciplina = p_id_disciplina
    ) THEN
        RAISE EXCEPTION 'La disciplina seleccionada no existe';
    END IF;

    -- Guardar el alumno o reutilizarlo si su DNI ya existe
    INSERT INTO alumno (dni, nombre, apellido, telefono)
    VALUES (
        p_dni,
        TRIM(p_nombre),
        TRIM(p_apellido),
        TRIM(p_telefono)
    )
    ON CONFLICT (dni)
    DO UPDATE SET
        nombre = EXCLUDED.nombre,
        apellido = EXCLUDED.apellido,
        telefono = EXCLUDED.telefono
    RETURNING id_alumno INTO v_id_alumno;

    -- Crear la inscripción usando el ID del alumno
    INSERT INTO inscripcion (
        id_alumno,
        id_disciplina,
        fecha_inscripcion,
        estado
    )
    VALUES (
        v_id_alumno,
        p_id_disciplina,
        CURRENT_DATE,
        'Activa'
    )
    RETURNING id_inscripcion INTO v_id_inscripcion;

    -- Devolver el resultado
    RETURN jsonb_build_object(
        'mensaje', 'Inscripcion registrada correctamente',
        'id_alumno', v_id_alumno,
        'id_inscripcion', v_id_inscripcion
    );

END;
$$;


