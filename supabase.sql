-- ============================================
-- 14. VERIFICACIÓN DE LA LÓGRICA DE BORRADO (se puede ejecutar solo)
-- Muestra qué registros todavía están vinculados (no se pueden
-- eliminar desde index.html) y cuáles ya se pueden eliminar.
-- ============================================

-- Entrenadores: solo se pueden eliminar cuando ya no tienen disciplina
SELECT
    e.id_entrenador,
    e.nombre || ' ' || e.apellido AS entrenador,
    d.nombre_disciplina,
    CASE
        WHEN e.id_disciplina IS NULL THEN 'SE PUEDE ELIMINAR'
        ELSE 'BLOQUEADO (primero elimina su disciplina)'
    END AS estado_borrado
FROM entrenador e
LEFT JOIN disciplina d ON d.id_disciplina = e.id_disciplina
ORDER BY e.id_entrenador;

-- Inscripciones: solo se pueden eliminar cuando ya no tienen
-- alumno o ya no tienen disciplina
SELECT
    i.id_inscripcion,
    COALESCE(a.nombre || ' ' || a.apellido, '—') AS alumno,
    COALESCE(d.nombre_disciplina, '—') AS disciplina,
    CASE
        WHEN i.id_alumno IS NULL OR i.id_disciplina IS NULL THEN 'SE PUEDE ELIMINAR'
        ELSE 'BLOQUEADO (primero elimina su alumno o su disciplina)'
    END AS estado_borrado
FROM inscripcion i
LEFT JOIN alumno a ON a.id_alumno = i.id_alumno
LEFT JOIN disciplina d ON d.id_disciplina = i.id_disciplina
ORDER BY i.id_inscripcion;


-- ============================================
-- 15. REGLAS DE ELIMINACIÓN (documentación)
-- ============================================
--
-- Tablas PADRE:  alumno, disciplina
--   -> Se eliminan NORMAL desde index.html (un solo "Sí, eliminar").
--   -> Se borra SOLO su propio registro. Nada más se borra en cascada.
--
-- Tablas CON FK:  entrenador, inscripcion
--   -> Su botón es un tachito (gris mientras estén vinculados).
--   -> NO se pueden eliminar directamente:
--        * entrenador:  mientras tenga disciplina.
--        * inscripcion: mientras tenga alumno Y disciplina.
--   -> Flujo correcto:
--        1) Eliminas la disciplina -> el entrenador queda sin disciplina
--           y recién ahí se puede eliminar el entrenador.
--        2) Eliminas el alumno (o la disciplina) -> la inscripción queda
--           sin alumno (o sin disciplina) y recién ahí se puede eliminar.
--
-- En la base (ON DELETE SET NULL):
--   -> Borrar un disciplina pone en NULL el id_disciplina de sus
--      entrenadores e inscripciones (no los borra).
--   -> Borrar un alumno pone en NULL el id_alumno de sus inscripciones.
--   -> Por eso los registros "huérfanos" siguen existiendo y se pueden
--      eliminar desde su propia vista.
-- ============================================


